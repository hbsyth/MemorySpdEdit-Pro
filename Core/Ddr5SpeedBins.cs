    public static bool TryGet(string name, out Ddr5SpeedBin bin) =>
        All.TryGetValue(name, out bin!);

    /// <summary>
    /// Apply speed bin into a Ddr5ProfileEdit (and related voltage/cmd fields).
    /// Port of apply_speed_bin / apply_speed_bin_to_xmp / apply_speed_bin_to_expo.
    /// </summary>
    public static bool TryApply(string binName, Ddr5ProfileKind kind, out Ddr5ProfileEdit edit, out string error)
    {
        edit = new Ddr5ProfileEdit();
        error = "";
        if (!TryGet(binName, out var b))
        {
            error = $"未知 Speed Bin: {binName}";
            return false;
        }

        static int Ns2Ps(double ns) => (int)Math.Round(ns * 1000.0);

        int mct = Ns2Ps(b.TckMinNs);
        edit.TckPs = mct;
        edit.SupportedCas = new HashSet<int>(b.SupportedCl);
        edit.TclPs = Ns2Ps(b.TaaNs);
        edit.TrcdPs = Ns2Ps(b.TrcdNs);
        edit.TrpPs = Ns2Ps(b.TrpNs);
        edit.TrasPs = Ns2Ps(b.TrasNs);
        edit.TrcPs = Ns2Ps(b.TrcNs);
        edit.TwrPs = Ns2Ps(b.TwrNs);
        edit.Trfc1Ns = (int)Math.Round(b.Trfc1Ns);
        edit.Trfc2Ns = (int)Math.Round(b.Trfc2Ns);
        edit.TrfcsbNs = (int)Math.Round(b.Trfc4Ns);

        int tWtrLPs = Ns2Ps(b.TwtrLNs);
        int tWtrSPs = Ns2Ps(b.TwtrSNs);
        int tRrdLPs = Ns2Ps(b.TrrdLNs);
        int tFawPs = Ns2Ps(b.TfawNs);
        int tCcdLPs = Ns2Ps(Math.Max(b.TrrdLNs, 4.0));
        int tRtpPs = Math.Max(tWtrLPs, Ns2Ps(7.5));

        edit.TrrdlPs = tRrdLPs;
        edit.TccdLPs = tCcdLPs;
        edit.TccdLWrPs = Math.Max(32 * mct, 20000);
        edit.TccdLWr2Ps = Math.Max(16 * mct, 10000);
        edit.TfawPs = tFawPs;
        edit.TccdLWtrPs = tWtrLPs;
        edit.TccdSWtrPs = tWtrSPs;
        edit.TrtpPs = tRtpPs;

        // Lower limits (XMP/JEDEC path; EXPO only sets WR limits in Python)
        edit.TccdLWrMin = 32;
        edit.TccdLWr2Min = 16;

        if (kind != Ddr5ProfileKind.Expo)
        {
            edit.TrrdlMin = Math.Max(4, SpdUtils.TimeToTicksDdr5(tRrdLPs, mct));
            edit.TccdLMin = Math.Max(4, SpdUtils.TimeToTicksDdr5(tCcdLPs, mct));
            edit.TfawMin = Math.Max(20, SpdUtils.TimeToTicksDdr5(tFawPs, mct));
            edit.TccdLWtrMin = Math.Max(4, SpdUtils.TimeToTicksDdr5(tWtrLPs, mct));
            edit.TccdSWtrMin = Math.Max(2, SpdUtils.TimeToTicksDdr5(tWtrSPs, mct));
            edit.TrtpMin = Math.Max(6, SpdUtils.TimeToTicksDdr5(tRtpPs, mct));
        }

        if (kind == Ddr5ProfileKind.Xmp)
        {
            edit.VddCv = 110;
            edit.VddqCv = 110;
            edit.VppCv = 180;
            edit.VmemCv = 110;
            edit.CommandRate = 2;
        }
        else if (kind == Ddr5ProfileKind.Expo)
        {
            edit.VddCv = 110;
            edit.VddqCv = 110;
            edit.VppCv = 180;
        }

        return true;
    }
